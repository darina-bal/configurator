export interface MediaSlide {
  /** Ключ слайда. Пока он не меняется, слайд переиспользуется (меняется лишь содержимое). */
  id: string;
  /** Изображение, видеофайл (<video>) или плеер стороннего сервиса (iframe). */
  kind: 'image' | 'video' | 'embed';
  src: string;
  /** Для изображения — alt, для видео и плеера — название. */
  alt: string;
  /** Подпись для подсказки миниатюры. */
  label: string;
  /** Постер видео; также картинка миниатюры видео-слайда. */
  poster?: string;
  /** Как вписывать изображение в кадр 16:9: заполнить (по умолчанию) или целиком (чертёж). */
  fit?: 'cover' | 'contain';
}
