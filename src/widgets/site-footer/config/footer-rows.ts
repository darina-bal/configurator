/** Вложенный список внутри раздела («Партнеры», «Дилеры»): раскрывается по нажатию. */
export interface FooterGroup {
  label: string;
  /** Названия пунктов; каждый — ссылка-заглушка. */
  links: readonly string[];
}

/** Раздел-аккордеон со списком пунктов; `note` — примечание под списком. */
export interface FooterSection {
  title: string;
  /** Пункт — название ссылки-заглушки или вложенный список. */
  items: readonly (string | FooterGroup)[];
  note?: string;
}

/** Строка-заглушка без списка («Кабинет дизайнера»): выглядит как раздел, но раскрывать в ней нечего. */
interface FooterLinkRow {
  title: string;
}

type FooterRow = FooterSection | FooterLinkRow;

export function isFooterSection(row: FooterRow): row is FooterSection {
  return 'items' in row;
}

export function isFooterGroup(item: string | FooterGroup): item is FooterGroup {
  return typeof item !== 'string';
}

